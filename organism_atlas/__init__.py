"""Организм 360: интерактивная схема тела с викториной и 3D-просмотром органов.

Что внутри (по сравнению со старой версией):
  * схема тела рисуется один раз при запуске в Pillow с суперсэмплингом (сглаживание по площади
    покрытия) сразу в реальном разрешении экрана, поэтому края ровные и чёткие;
  * тело: объёмное освещение, скелет, сосуды, а каждый орган нарисован отдельно: свет и тени
    считаются по карте высот, текстуры процедурные (дольки лёгких и бронхи, извилины мозга,
    мышечные волокна и коронарные сосуды сердца, складки толстой кишки и т. д.);
  * подсветка при наведении и закраска в викторине повторяют контур органа (маски по пикселям);
  * 3D-просмотр рисует собственный сглаженный рендер (попиксельный свет, 3D-текстуры, AO) на видеокарте,
    а без неё - тот же рендер на numpy;
  * интерфейс на Qt: схема и 3D рисуются в пикселях экрана, поэтому на экранах с масштабом ничего не размывается.

Нужны: Python 3, numpy, Pillow, PySide6, moderngl (requirements.txt).
"""

