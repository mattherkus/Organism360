from ..geometry import CX, P, sym


HEAD_HALF = [(0, 18), (13, 19.5), (24, 25), (31, 36), (34.5, 50), (34, 66), (30, 82), (22, 96), (11, 106), (0, 110)]
TORSO_HALF = [(16, 96), (17, 118), (27, 130), (46, 139), (66, 146), (80, 151), (88, 160), (86, 176), (66, 190),
              (63, 216), (66, 240), (66, 264), (64, 288), (63, 314), (65, 338), (66, 360), (58, 384),
              (34, 396), (0, 399)]
LEG = ([(33, 350), (32, 400), (29, 460), (27, 520), (26.5, 575), (24, 640), (22, 688)],
       [66, 60, 49, 42, 43, 31, 23])
ARM = ([(78, 168), (82, 200), (87, 240), (91, 277), (97, 318), (101, 352), (104, 380)],
       [30, 34, 33, 28, 28, 24, 19])
PALM = [(93, 376), (95, 398), (97, 418), (108, 425), (118, 421), (122, 404), (120, 386), (115, 377)]
FINGERS = [  # основание x, длина, ширина, отклонение кончика
    (99, 27, 6.0, -1.5), (105, 35, 6.6, 0.0), (111, 39, 6.8, 1.5), (117, 35, 6.4, 3.5)]
