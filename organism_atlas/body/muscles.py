"""Поверхностные мышцы (рисуются на слое Ink): шея, плечи, грудь, живот, руки и ноги до стоп.

Каждая мышца - брюшко (трубка или многоугольник с объёмом) и волокна вдоль неё: тонкие бороздки на карте
высоты, которые свет превращает в штриховку. Торс по большей части закрыт органами, поэтому мышцы заметнее
всего на шее, плечах, руках и бёдрах. K.part(ключ) отмечает, какая мышца рисуется дальше (маски для клика
строит structures.py).
"""

import numpy as np

from ..geometry import CX, P
from .skeleton import RIBS, rib


def _fibers(K, pts, widths, n, depth=0.35):
    """n бороздок вдоль трубки pts (ширины widths): тонкие линии на карте высоты чуть ниже брюшка"""
    pts = np.asarray(pts, np.float64)
    w = np.interp(np.linspace(0, 1, len(pts)), np.linspace(0, 1, len(widths)), widths)
    d = np.gradient(pts, axis=0)
    nrm = np.stack([-d[:, 1], d[:, 0]], 1)
    nrm /= np.linalg.norm(nrm, axis=1, keepdims=True) + 1e-9
    for j in range(n):
        f = (j + 1) / (n + 1) - 0.5                        # от -0.5 до 0.5 поперёк брюшка
        line = pts + nrm * (w * 0.8 * f)[:, None]
        K.hgt.line([tuple(p) for p in line], 0.6, v=int(255 * depth))


def belly(K, pts, widths, fibers=3):
    """мышечное брюшко-трубка с волокнами"""
    K.tube(pts, widths)
    _fibers(K, pts, widths, fibers)


def sheet(K, pts, lines=(), steps=14):
    """плоская мышца (многоугольник) и волокна lines - отрезки [(x, y), ...] вдоль неё.
    Высота - пологий купол: вложенные копии контура, сжатые к центру, всё выше (иначе мышца плоская)"""
    K.cov.poly(pts)
    c = np.mean(np.asarray(pts, np.float64), axis=0)
    for k in range(steps):
        f = 1 - k / (steps + 1)
        K.hgt.poly([(c[0] + (x - c[0]) * f, c[1] + (y - c[1]) * f) for x, y in pts], int(255 * (k + 1) / steps))
    for ln in lines:
        K.hgt.line(ln, 0.6, v=70)


def intercostals(K):
    """межрёберные мышцы - полосы между соседними рёбрами (под ними: слой мышц лежит под скелетом)"""
    for i in range(len(RIBS) - 1):
        a, b = rib(i), rib(i + 1)
        n = min(len(a), len(b))
        mid = [((xa + xb) / 2, (ya + yb) / 2) for (xa, ya), (xb, yb) in zip(a[:n], b[:n])]
        gap = [max(abs(yb - ya), 4.0) for (_xa, ya), (_xb, yb) in zip(a[:n], b[:n])]
        for s in (1, -1):
            pts = P(mid, s < 0)
            K.tube(pts, gap)
            for j in range(len(pts) - 1):                  # волокна наискосок: вниз и вперёд
                (x0, y0), (x1, y1) = pts[j], pts[j + 1]
                K.hgt.line([(x0, y0 - gap[j] * .3), (x1, y1 + gap[j + 1] * .3)], 0.6, v=70)


def muscles(K):
    """K - объект Ink; мышцы в проектных координатах (как кости и сосуды)"""
    K.part("intercostals")
    intercostals(K)
    for s in (1, -1):
        f = s < 0
        # шея: лестничные - глубже, от шейных позвонков к первому ребру; подъязычная - тонкая лента спереди
        K.part("scalenes")
        belly(K, P([(10, 108), (15, 122), (21, 136), (26, 148)], f), [4, 6.5, 6.5, 5], 2)
        K.part("sternohyoid")
        belly(K, P([(4, 112), (5, 126), (5, 140), (5, 152)], f), [3.6, 4.6, 4.6, 4], 1)
        # грудино-ключично-сосцевидная - от уха к грудине
        K.part("sternocleidomastoid")
        belly(K, P([(29, 72), (24, 100), (16, 128), (8, 150)], f), [6, 8.5, 8, 6], 2)
        # трапециевидная - скат от шеи к плечу
        K.part("trapezius")
        sheet(K, P([(14, 104), (22, 118), (44, 136), (68, 144), (74, 150), (56, 148), (30, 140), (16, 128)], f),
              [P([(18, 116), (60, 144)], f), P([(16, 124), (50, 144)], f)])
        # дельтовидная - шапка плеча
        K.part("deltoid")
        sheet(K, P([(64, 146), (78, 147), (89, 158), (90, 178), (86, 200), (82, 208), (77, 192), (71, 166)], f),
              [P([(70, 150), (82, 200)], f), P([(78, 150), (86, 196)], f), P([(86, 160), (85, 200)], f)])
        # большая грудная - веер от грудины и ключицы к плечу
        K.part("pectoralis")
        sheet(K, P([(9, 156), (36, 152), (62, 154), (74, 168), (72, 182), (54, 206), (32, 220), (12, 222),
                    (8, 190)], f),
              [P([(12, 165), (70, 172)], f), P([(12, 185), (70, 176)], f), P([(14, 205), (68, 180)], f),
               P([(30, 216), (66, 182)], f)])
        # прямая мышца живота с сухожильными перемычками
        K.part("rectus_abdominis")
        sheet(K, P([(3, 226), (21, 228), (23, 262), (22, 300), (19, 340), (12, 372), (3, 376)], f))
        for y in (250, 278, 306):
            K.hgt.line(P([(4, y), (21, y + 2)], f), 1.6, v=40)
        # наружная косая - бок живота
        K.part("external_oblique")
        sheet(K, P([(30, 226), (56, 214), (64, 240), (65, 280), (62, 320), (44, 336), (28, 300), (26, 260)], f),
              [P([(58, 222), (30, 262)], f), P([(62, 250), (32, 292)], f), P([(62, 284), (40, 320)], f)])
        # руки: двуглавая плеча, плечелучевая; на предплечье - круглый пронатор, лучевой и локтевой сгибатели
        # запястья (ладонью вперёд локтевой край - ближе к телу)
        K.part("biceps")
        belly(K, P([(79, 194), (82, 226), (86, 256), (89, 276)], f), [12, 21, 18, 9], 4)
        K.part("brachioradialis")
        belly(K, P([(93, 274), (98, 302), (101, 335), (103, 366)], f), [12, 15, 11, 6], 3)
        K.part("flexor_carpi_ulnaris")
        belly(K, P([(84, 286), (87, 314), (91, 342), (96, 372)], f), [7, 9, 7, 3.5], 2)
        K.part("flexor_carpi_radialis")
        belly(K, P([(87, 290), (92, 316), (97, 344), (102, 371)], f), [6, 8.5, 6, 3], 2)
        K.part("pronator_teres")
        belly(K, P([(84, 280), (90, 293), (97, 309)], f), [6, 8, 5], 2)
        # бёдра: прямая, латеральная и медиальная широкие, портняжная (к внутренней стороне голени), приводящие
        K.part("adductors")
        belly(K, P([(12, 384), (16, 420), (21, 460), (24, 500)], f), [10, 15, 12, 8], 2)
        K.part("vastus_medialis")
        belly(K, P([(22, 450), (19, 478), (19, 500), (24, 516)], f), [7, 13, 14, 8], 3)
        K.part("rectus_femoris")
        belly(K, P([(40, 376), (39, 420), (35, 470), (31, 520)], f), [13, 19, 17, 12], 3)
        K.part("vastus_lateralis")
        belly(K, P([(56, 382), (54, 420), (48, 470), (42, 520)], f), [10, 16, 15, 10], 3)
        K.part("sartorius")
        belly(K, P([(60, 364), (48, 400), (32, 450), (18, 510), (16, 530), (20, 545)], f), [5, 6, 6, 5, 4.5, 4], 1)
        # голень: икроножная (её медиальная головка видна спереди у внутреннего края), передняя большеберцовая
        # у гребня большеберцовой кости и длинная малоберцовая снаружи
        K.part("gastrocnemius")
        belly(K, P([(14, 540), (10, 568), (10, 600), (14, 632)], f), [8, 12, 11, 5], 3)
        K.part("tibialis_anterior")
        belly(K, P([(33, 534), (33, 568), (31, 608), (28, 648), (22, 690)], f), [9, 11, 9, 5, 3], 3)
        K.part("fibularis_longus")
        belly(K, P([(42, 540), (42, 575), (40, 615), (37, 652), (36, 680)], f), [7, 9, 7, 4, 3], 2)
    # сухожильный центр живота - белая линия между прямыми мышцами
    K.part("rectus_abdominis")
    K.cut(CX, 300, 1.3, 74)
