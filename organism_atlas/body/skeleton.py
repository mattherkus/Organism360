"""Скелет (кости рисуются на слое Ink)."""

from ..geometry import CX, P, rrect


def skeleton(K):
    """K - объект Ink; рисуем кости в проектных координатах"""
    # череп
    K.cov.ellipse(CX, 50, 29, 33)
    K.hgt.ellipse(CX, 50, 29, 33, 150)
    for s in (1, -1):
        K.cut(CX + s * 12, 78, 7.5, 6)                      # глазницы
    K.cut(CX, 90, 2.8, 4)
    K.line([(CX - 27, 80), (CX - 25, 95), (CX - 11, 107), (CX + 11, 107), (CX + 25, 95), (CX + 27, 80)], 3.4)
    K.poly(rrect(CX, 99, 18, 5.5, 2.5))
    # позвоночник
    for i in range(7):                                       # шейные
        K.poly(rrect(CX, 104 + i * 5.2, 11 + i * .4, 4.2, 1.5))
    for i in range(12):                                      # грудные
        y = 142 + i * 10.1
        K.poly(rrect(CX, y, 13 + i * .55, 7.6, 2))
        K.line([(CX - 10 - i * .3, y), (CX + 10 + i * .3, y)], 1.3, smooth=False)
    for i in range(5):                                       # поясничные
        y = 267 + i * 11.4
        K.poly(rrect(CX, y, 21 + i * .8, 9, 2.6))
        K.line([(CX - 17, y), (CX + 17, y)], 1.8, smooth=False)
    K.poly([(CX - 15, 322), (CX + 15, 322), (CX + 11, 352), (CX + 3, 377), (CX - 3, 377), (CX - 11, 352)])
    for yy in (336, 349, 361):
        K.cut(CX - 4.5, yy, 1.6, 1.8)
        K.cut(CX + 4.5, yy, 1.6, 1.8)
    # грудина, ключицы
    K.poly([(CX - 8, 151), (CX + 8, 151), (CX + 6, 166), (CX + 5, 222), (CX + 2, 238), (CX - 2, 238),
            (CX - 5, 222), (CX - 6, 166)], smooth=False)
    for s in (1, -1):
        K.line(P([(6, 153), (30, 147), (52, 150), (70, 146)], s < 0), 3.6)
    # рёбра: (y у позвоночника, y сбоку, y спереди, полуширина)
    RIBS = [(148, 152, 160, 30), (158, 166, 178, 40), (167, 180, 195, 48), (176, 193, 211, 53),
            (185, 206, 224, 56), (194, 218, 235, 58), (203, 230, 245, 59), (212, 240, 253, 58),
            (221, 249, 259, 56), (230, 257, 264, 52), (240, 263, 266, 44), (250, 268, 269, 36)]
    for i, (ys, yl, yf, R) in enumerate(RIBS):
        xf = 7 if i < 7 else (16, 24, 32, 0, 0)[i - 7]
        pts = [(7, ys), (R * .62, ys + (yl - ys) * .25), (R, yl)]
        if i < 10:
            pts += [(R * .78 + xf * .22, yl + (yf - yl) * .55), (xf, yf)]
        for s in (1, -1):
            K.line(P(pts, s < 0), 2.5 if i < 7 else 2.1)
    # таз
    for s in (1, -1):
        K.poly(P([(12, 322), (30, 306), (52, 300), (63, 308), (64, 326), (58, 344), (48, 356), (38, 362),
                  (28, 360), (16, 350)], s < 0))
        K.cut(CX + s * 25, 346, 11, 13)
        K.line(P([(36, 368), (20, 382), (4, 389)], s < 0), 6)
        K.line(P([(38, 372), (42, 390)], s < 0), 7)
        K.cut(CX + s * 25, 381, 5, 8)
        K.disc(CX + s * 36, 368, 9.5)
        # руки: плечевая, локтевая, лучевая
        K.tube(P([(76, 166), (80, 210), (87, 262), (90, 278)], s < 0), [15, 10, 11, 19])
        K.tube(P([(87, 284), (95, 330), (99, 372)], s < 0), [10, 7, 7.5])
        K.tube(P([(95, 284), (100, 330), (105, 374)], s < 0), [7, 6, 11])
        K.disc(CX + s * 104, 386, 8)
        for bx, ln, _wd, off in ((99, 27, 6.0, -1.5), (105, 35, 6.6, 0), (111, 39, 6.8, 1.5), (117, 35, 6.4, 3.5)):
            K.line(P([(bx - 1 + off * .1, 396), (bx, 418)], s < 0), 3.4)
            for a, b in ((421, 421 + ln * .38), (421 + ln * .42, 421 + ln * .7), (421 + ln * .74, 420 + ln * .96)):
                K.line(P([(bx + off * (a - 421) / ln, a), (bx + off * (b - 421) / ln, b)], s < 0), 2.6)
        K.line(P([(112, 392), (124, 410), (128, 440)], s < 0), 3.6)
        # ноги: бедренная, большая и малая берцовые
        K.disc(CX + s * 36, 366, 9)
        K.line(P([(36, 366), (47, 375)], s < 0), 8)
        K.tube(P([(44, 374), (38, 440), (31, 500), (28, 514)], s < 0), [14, 11, 12, 26])
        K.cov.ellipse(CX + s * 27, 514, 8, 9)
        K.hgt.ellipse(CX + s * 27, 514, 8, 9, 200)
        K.tube(P([(27, 530), (26, 600), (23, 683)], s < 0), [22, 10, 15])
        K.tube(P([(38, 540), (35, 610), (33, 678)], s < 0), [6, 5, 9])
        for tx, ty in ((14, 718), (23, 723), (31, 723), (39, 719), (47, 713)):
            K.line(P([(22, 692), (tx + (23 - tx) * .3, 702), (tx, ty)], s < 0), 3.6)
