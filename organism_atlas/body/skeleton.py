"""Скелет (кости рисуются на слое Ink). K.part(ключ) отмечает, какая кость рисуется дальше: по этим отметкам
structures.py строит маски для клика по костям."""

from ..geometry import CX, P, rrect

# рёбра: (y у позвоночника, y сбоку, y спереди, полуширина); по ним же рисуются межрёберные мышцы (muscles.py)
RIBS = [(148, 152, 160, 30), (158, 166, 178, 40), (167, 180, 195, 48), (176, 193, 211, 53),
        (185, 206, 224, 56), (194, 218, 235, 58), (203, 230, 245, 59), (212, 240, 253, 58),
        (221, 249, 259, 56), (230, 257, 264, 52), (240, 263, 266, 44), (250, 268, 269, 36)]
FINGERS = ((99, 27, -1.5), (105, 35, 0.0), (111, 39, 1.5), (117, 35, 3.5))    # основание x, длина, отклонение
# кости запястья: проксимальный ряд (ладьевидная ... гороховидная) и дистальный (трапеция ... крючковидная)
CARPALS = [(113, 382), (108, 381), (103, 381), (98, 383), (115, 390), (110, 390), (105, 390), (100, 391)]


def rib(i):
    """опорные точки ребра i (правая половина): от позвоночника вбок и, кроме двух нижних, вперёд к грудине"""
    ys, yl, yf, R = RIBS[i]
    xf = 7 if i < 7 else (16, 24, 32, 0, 0)[i - 7]
    pts = [(7, ys), (R * .62, ys + (yl - ys) * .25), (R, yl)]
    if i < 10:
        pts += [(R * .78 + xf * .22, yl + (yf - yl) * .55), (xf, yf)]
    return pts


def skeleton(K):
    """K - объект Ink; рисуем кости в проектных координатах"""
    # череп
    K.part("skull")
    K.cov.ellipse(CX, 50, 29, 33)
    K.hgt.ellipse(CX, 50, 29, 33, 150)
    for s in (1, -1):
        K.cut(CX + s * 12, 78, 7.5, 6)                      # глазницы
    K.cut(CX, 90, 2.8, 4)
    K.part("mandible")
    K.line([(CX - 27, 80), (CX - 25, 95), (CX - 11, 107), (CX + 11, 107), (CX + 25, 95), (CX + 27, 80)], 3.4)
    K.poly(rrect(CX, 99, 18, 5.5, 2.5))
    # позвоночник
    K.part("spine")
    for i in range(7):                                       # шейные
        K.poly(rrect(CX, 104 + i * 5.2, 11 + i * .4, 4.2, 1.5))
    for i in range(12):                                      # грудные
        y = 142 + i * 10.1
        K.poly(rrect(CX, y, 13 + i * .55, 7.6, 2))
        K.line([(CX - 10 - i * .3, y), (CX + 10 + i * .3, y)], 1.3, smooth=False)
    for i in range(5):                                       # поясничные
        y = 267 + i * 11.4
        K.poly(rrect(CX, y, 21 + i * .8, 9, 2.6))
        K.line([(CX - 17, y), (CX + 17, y)], 1.8, smooth=False)
    K.part("sacrum")
    K.poly([(CX - 15, 322), (CX + 15, 322), (CX + 11, 352), (CX + 3, 377), (CX - 3, 377), (CX - 11, 352)])
    for yy in (336, 349, 361):
        K.cut(CX - 4.5, yy, 1.6, 1.8)
        K.cut(CX + 4.5, yy, 1.6, 1.8)
    # грудина, ключицы
    K.part("sternum")
    K.poly([(CX - 8, 151), (CX + 8, 151), (CX + 6, 166), (CX + 5, 222), (CX + 2, 238), (CX - 2, 238),
            (CX - 5, 222), (CX - 6, 166)], smooth=False)
    K.part("clavicle")
    for s in (1, -1):
        K.line(P([(6, 153), (30, 147), (52, 150), (70, 146)], s < 0), 3.6)
    # лопатка - за рёбрами (рисуется раньше них), спереди видна её наружная часть у плеча
    K.part("scapula")
    for s in (1, -1):
        blade = P([(44, 152), (56, 150), (66, 146), (73, 145), (76, 150), (72, 158), (71, 170), (66, 186),
                   (60, 212), (55, 232), (49, 228), (44, 206), (41, 180)], s < 0)
        K.cov.poly(blade)
        K.hgt.poly(blade, 90)
        K.line(P([(66, 152), (62, 159), (57, 162)], s < 0), 3)              # клювовидный отросток
    K.part("ribs")
    for i in range(len(RIBS)):
        for s in (1, -1):
            K.line(P(rib(i), s < 0), 2.5 if i < 7 else 2.1)
    # таз
    for s in (1, -1):
        K.part("pelvis")
        K.poly(P([(12, 322), (30, 306), (52, 300), (63, 308), (64, 326), (58, 344), (48, 356), (38, 362),
                  (28, 360), (16, 350)], s < 0))
        K.cut(CX + s * 25, 346, 11, 13)
        K.line(P([(36, 368), (20, 382), (4, 389)], s < 0), 6)
        K.line(P([(38, 372), (42, 390)], s < 0), 7)
        K.cut(CX + s * 25, 381, 5, 8)
        K.disc(CX + s * 36, 368, 9.5)
        # руки: плечевая, локтевая, лучевая
        K.part("humerus")
        K.tube(P([(76, 166), (80, 210), (87, 262), (90, 278)], s < 0), [15, 10, 11, 19])
        K.part("ulna")
        K.tube(P([(87, 284), (95, 330), (99, 372)], s < 0), [10, 7, 7.5])
        K.part("radius")
        K.tube(P([(95, 284), (100, 330), (105, 374)], s < 0), [7, 6, 11])
        # кисть: восемь костей запястья в два ряда, пять пястных и фаланги пальцев
        K.part("carpals")
        for x, y in CARPALS:
            K.disc(CX + s * x, y, 3)
        K.part("metacarpals")
        for bx, _ln, off in FINGERS:
            K.line(P([(bx - 1 + off * .1, 396), (bx, 418)], s < 0), 3.4)
        K.line(P([(115, 394), (119, 401), (122, 408)], s < 0), 3.6)          # пястная кость большого пальца
        K.part("phalanges")
        for bx, ln, off in FINGERS:
            for a, b in ((421, 421 + ln * .38), (421 + ln * .42, 421 + ln * .7), (421 + ln * .74, 420 + ln * .96)):
                K.line(P([(bx + off * (a - 421) / ln, a), (bx + off * (b - 421) / ln, b)], s < 0), 2.6)
        K.line(P([(123, 411), (126, 422)], s < 0), 3.2)                      # у большого пальца - две фаланги
        K.line(P([(126.5, 426), (128, 440)], s < 0), 3)
        # ноги: бедренная, надколенник, большая и малая берцовые, кости стопы
        K.part("femur")
        K.disc(CX + s * 36, 366, 9)
        K.line(P([(36, 366), (47, 375)], s < 0), 8)
        K.tube(P([(44, 374), (38, 440), (31, 500), (28, 514)], s < 0), [14, 11, 12, 26])
        K.part("patella")
        K.cov.ellipse(CX + s * 27, 514, 8, 9)
        K.hgt.ellipse(CX + s * 27, 514, 8, 9, 200)
        K.part("tibia")
        K.tube(P([(27, 530), (26, 600), (23, 683)], s < 0), [22, 10, 15])
        K.part("fibula")
        K.tube(P([(38, 540), (35, 610), (33, 678)], s < 0), [6, 5, 9])
        K.part("foot")
        K.poly(P([(15, 689), (27, 686), (35, 692), (32, 701), (20, 704), (13, 698)], s < 0))   # предплюсна
        for tx, ty in ((14, 718), (23, 723), (31, 723), (39, 719), (47, 713)):
            K.line(P([(22, 696), (tx + (23 - tx) * .3, 704), (tx, ty)], s < 0), 3.6)
