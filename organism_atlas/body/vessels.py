"""Артерии и вены - по ходу настоящих сосудов (вид спереди, ладони вперёд: большой палец снаружи).

Артерии: аорта (её же рисует орган «Аорта» поверх слоёв), почечные и нижняя брыжеечная; общие сонные с делением
на внутреннюю и наружную (лицевая и поверхностная височная ветви), позвоночные; подключичная - подмышечная -
плечевая (с глубокой артерией плеча), в локтевой ямке деление на лучевую (снаружи, к большому пальцу) и локтевую
(внутри), ладонные дуги и пальцевые артерии; внутренние грудные - верхние и нижние надчревные; общие подвздошные
с делением на внутреннюю и наружную, бедренная с глубокой артерией бедра; под коленом подколенная делится на переднюю
большеберцовую (между берцовыми костями, на стопе - тыльная артерия стопы) и заднюю большеберцовую (у внутренней
лодыжки).
Вены: внутренние и наружные яремные, лицевые; подключичная - подмышечная - плечевая, поверхностные латеральная
(головная) и медиальная (основная) подкожные вены руки, срединная вена локтя между ними; нижняя полая (её же
рисует орган «Полые вены») с почечными венами (левая длиннее и идёт перед аортой); общие, наружные и внутренние
подвздошные, бедренная - медиальнее артерии, подколенная и большеберцовые рядом с артериями, большая подкожная
вена ноги - от тыльной венозной дуги стопы впереди внутренней лодыжки и по внутренней стороне голени и бедра.
Вены у конечностей лежат рядом с одноимёнными артериями, чуть медиальнее."""

from ..geometry import P
from ..organs import aorta, vena_cava
from ..organs.aorta import DESCENDING, DESCENDING_W
from ..organs.vena_cava import CONFLUENCE, IVC, IVC_W

FINGERS = ((99, 27, -1.5), (105, 35, 0.0), (111, 39, 1.5), (117, 35, 3.5))   # основание x, длина, отклонение

HILUM = (22.5, 322, 328)        # ворота почек: dx и y (левая почка выше правой), как в organs/kidneys.py
BIFURCATION = DESCENDING[-1]    # деление аорты на общие подвздошные артерии


def arteries(A):
    # аорта (под органом «Аорта»: видна, если орган скрыт) и её непарные ветви живота
    A.tube(P(DESCENDING), DESCENDING_W)
    for path, widths in aorta.BRANCHES:
        A.tube(P(path), widths)
    A.tube(P(aorta.ASCENDING), aorta.ASCENDING_W)
    A.tube(P([(4, 304), (9, 312), (13, 324), (14, 338)]), [2.2, 2, 1.8, 1.6])          # нижняя брыжеечная
    for s in (1, -1):
        f = s < 0
        hy = HILUM[2] if f else HILUM[1]
        # почечные артерии - к воротам почек
        A.tube(P([(4, 312), (12, 315), (HILUM[0] - 2, hy - 1)], f), [3.2, 3, 2.6])
        # общая подвздошная - наружная подвздошная - бедренная (под паховой связкой, над головкой бедра)
        A.tube(P([BIFURCATION, (9, 333), (16, 343)], f), [6, 5.6, 5.2])
        A.tube(P([(16, 343), (25, 350), (33, 359), (35, 372), (34, 396), (30, 426), (25, 458), (20, 490),
                  (16, 518)], f), [5, 4.8, 4.6, 4.4, 4.1, 3.8, 3.5, 3.2, 3])
        A.tube(P([(16, 343), (15, 354), (13, 366), (11, 374)], f), [3.6, 3.2, 2.8, 2.2])     # внутренняя подвздошная
        # глубокая артерия бедра и её латеральная огибающая ветвь
        A.tube(P([(35, 376), (40, 388), (42, 414), (41, 446), (38, 478)], f), [3.4, 3.2, 2.9, 2.5, 2])
        A.tube(P([(40, 388), (48, 391), (55, 398)], f), [2, 1.7, 1.3])
        # подколенная (за коленом) делится на переднюю большеберцовую - тыльную артерию стопы и заднюю большеберцовую
        A.tube(P([(16, 518), (19, 532), (23, 546)], f), [3, 2.9, 2.8])
        A.tube(P([(23, 546), (30, 556), (31, 600), (29, 646), (26, 684), (24, 698), (22, 712)], f),
               [2.4, 2.3, 2.1, 1.9, 1.7, 1.5, 1.2])
        A.tube(P([(23, 546), (20, 586), (17, 632), (16, 680), (18, 694)], f), [2.4, 2.2, 2, 1.7, 1.3])
        # нижняя надчревная (от наружной подвздошной вверх) навстречу верхней надчревной
        A.tube(P([(31, 357), (26, 340), (23, 318), (21, 296)], f), [1.8, 1.6, 1.4, 1.1])

        # шея и голова: общая сонная делится у верхнего края щитовидного хряща
        A.tube(P([(9, 152), (10, 138), (12, 122), (13, 110)], f), [4.6, 4.5, 4.3, 4.1])
        A.tube(P([(13, 110), (14, 98), (13, 86), (11, 74)], f), [3.4, 3.2, 3, 2.6])          # внутренняя сонная
        A.tube(P([(13, 110), (17, 102), (21, 93), (25, 82), (28, 70), (28, 58), (27, 46)], f),
               [3.2, 3, 2.7, 2.4, 2.2, 2, 1.8])                                           # наружная - поверхностная височная
        A.tube(P([(27, 50), (23, 40), (19, 31)], f), [1.6, 1.4, 1.1])                     # лобная ветвь
        A.tube(P([(28, 52), (30, 42), (29, 32)], f), [1.6, 1.4, 1.1])                     # теменная ветвь
        A.tube(P([(17, 102), (20, 97), (16, 90), (11, 84), (9, 75)], f), [2.2, 2, 1.8, 1.5, 1.1])     # лицевая
        A.tube(P([(12, 150), (9, 136), (7, 120), (6, 102)], f), [2.4, 2.2, 2, 1.8])          # позвоночная
        # внутренняя грудная вдоль края грудины - верхняя надчревная
        A.tube(P([(17, 149), (13, 168), (12, 205), (13, 236), (17, 258), (20, 282)], f),
               [2, 1.9, 1.8, 1.7, 1.5, 1.2])

        # рука: подключичная - подмышечная - плечевая
        A.tube(P([(9, 152), (18, 147), (30, 146), (44, 151), (56, 160), (66, 172), (73, 186), (76, 202),
                  (80, 236), (85, 266), (89, 284)], f), [5.2, 5.2, 5.1, 5, 4.8, 4.6, 4.3, 4, 3.8, 3.6, 3.4])
        A.tube(P([(77, 190), (83, 212), (90, 244), (94, 268)], f), [2.2, 2, 1.7, 1.3])      # глубокая артерия плеча
        # лучевая - к большому пальцу, глубокая ладонная дуга
        A.tube(P([(89, 284), (95, 302), (103, 330), (108, 354), (111, 374), (113, 384)], f),
               [3, 2.9, 2.7, 2.5, 2.3, 2.1])
        A.tube(P([(113, 384), (106, 390), (99, 391), (95, 388)], f), [1.9, 1.8, 1.6, 1.4])
        A.tube(P([(113, 384), (119, 396), (124, 412), (127, 430)], f), [1.6, 1.4, 1.2, 1])  # к большому пальцу
        # локтевая - поверхностная ладонная дуга и пальцевые артерии
        A.tube(P([(89, 284), (88, 304), (91, 330), (94, 354), (96, 374), (98, 386)], f),
               [3, 2.9, 2.7, 2.5, 2.3, 2.1])
        A.tube(P([(98, 386), (102, 400), (110, 405), (117, 401), (121, 394)], f), [2, 1.9, 1.7, 1.5, 1.3])
        for bx, ln, off in FINGERS:
            A.tube(P([(bx + 1, 403), (bx + 0.5, 416), (bx + off * .4, 417 + ln * .5), (bx + off * .8, 414 + ln)],
                     f), [1.4, 1.2, 1.1, 0.9])


def veins(V):
    # нижняя полая вена (под органом «Полые вены») и почечные вены
    V.tube(P(IVC), IVC_W)
    for path, widths in vena_cava.HEPATIC + vena_cava.BRACHIOCEPHALIC:
        V.tube(P(path), widths)
    V.tube(P(vena_cava.SVC), vena_cava.SVC_W)
    V.tube(P([(-6, 322), (-14, 325), (-HILUM[0] + 2, HILUM[2])]), [4, 3.8, 3.4])           # правая - короткая
    V.tube(P([(-6, 319), (4, 316), (14, 318), (HILUM[0] - 2, HILUM[1] + 1)]), [4, 3.8, 3.6, 3.4])  # левая - перед аортой
    for s in (1, -1):
        f = s < 0
        # общая подвздошная (левая длиннее) - наружная подвздошная - бедренная, медиальнее артерии
        V.tube(P([CONFLUENCE, (5, 338), (14, 349)] if s > 0 else [CONFLUENCE, (-10, 341), (-14, 349)]),
               [7, 6.6, 6.2])
        V.tube(P([(14, 349), (21, 356), (29, 364), (30, 380), (29, 404), (26, 432), (21, 462), (17, 492),
                  (13, 520)], f), [6, 5.8, 5.6, 5.3, 5, 4.6, 4.2, 3.8, 3.4])
        V.tube(P([(14, 349), (13, 360), (11, 370), (9, 378)], f), [4.2, 3.8, 3.2, 2.6])      # внутренняя подвздошная
        # подколенная - передняя и задняя большеберцовые, рядом с артериями и чуть медиальнее
        V.tube(P([(13, 520), (17, 535), (21, 548)], f), [3.4, 3.2, 3])
        V.tube(P([(21, 548), (28.5, 558), (29.5, 600), (27.5, 646), (24.5, 684)], f), [2.4, 2.3, 2.1, 1.9, 1.6])
        V.tube(P([(21, 548), (18.5, 588), (15.5, 634), (14.5, 680)], f), [2.6, 2.4, 2.2, 1.8])
        # большая подкожная вена: от тыльной венозной дуги стопы - впереди внутренней лодыжки, по внутренней
        # стороне голени и бедра, впадает в бедренную под паховой связкой
        V.tube(P([(29, 382), (23, 390), (16, 410), (11, 440), (9, 470), (9, 500), (10, 530), (9.5, 562), (10, 596),
                  (11.5, 632), (13.5, 668), (15, 692)], f),
               [3.4, 3.2, 3, 2.8, 2.6, 2.4, 2.2, 2.1, 2, 1.9, 1.8, 1.6])
        V.tube(P([(15, 692), (21, 701), (31, 705), (41, 707)], f), [1.6, 1.5, 1.4, 1.2])   # тыльная венозная дуга
        V.tube(P([(25, 387), (26, 366), (25, 344), (24, 322)], f), [1.6, 1.4, 1.2, 1])     # поверхностная надчревная

        # шея и голова: внутренняя яремная латеральнее сонной артерии, наружная - поверхностнее и снаружи
        V.tube(P([(17, 94), (18, 108), (19, 124), (18, 140), (15, 152)], f), [4.6, 5.4, 6, 6.4, 6.6])
        V.tube(P([(27, 88), (27, 104), (28, 122), (30, 140), (32, 152)], f), [2.6, 2.6, 2.5, 2.4, 2.4])
        V.tube(P([(28, 46), (29, 60), (28, 76), (27, 88)], f), [1.6, 1.8, 2.1, 2.4])         # поверхностная височная
        V.tube(P([(7, 74), (10, 84), (15, 93), (20, 102), (18, 112)], f), [1.4, 1.7, 2, 2.3, 2.6])  # лицевая

        # рука: подключичная - подмышечная - плечевая (рядом с артерией, медиальнее)
        V.tube(P([(12, 156), (26, 154), (42, 157), (54, 165), (63, 176), (69, 190), (72, 206), (76, 238),
                  (82, 268), (86, 286)], f), [6.4, 6.2, 6, 5.8, 5.4, 5, 4.4, 4, 3.6, 3.2])
        # основная (медиальная подкожная) вена: от локтевого края запястья, на середине плеча уходит вглубь
        V.tube(P([(95, 376), (90, 346), (86, 316), (82, 290), (76, 266), (72, 240), (72, 218)], f),
               [2.4, 2.6, 2.8, 3, 3.2, 3.4, 3.6])
        # головная (латеральная подкожная) вена: от лучевого края запястья вверх по наружной стороне руки,
        # в дельтовидно-грудной борозде - к подмышечной вене под ключицей
        V.tube(P([(112, 376), (109, 346), (104, 316), (99, 294), (96, 268), (94, 236), (92, 204), (87, 182),
                  (78, 169), (66, 164), (56, 166)], f),
               [2.2, 2.4, 2.6, 2.8, 2.8, 2.9, 3, 3, 3.1, 3.2, 3.3])
        V.tube(P([(98, 296), (90, 289), (82, 283)], f), [2.6, 2.6, 2.6])                     # срединная вена локтя
        V.tube(P([(103, 374), (101, 346), (97, 318), (92, 290)], f), [1.6, 1.8, 2, 2.2])     # срединная вена предплечья


def vessels(A, V):
    """A - артерии, V - вены (оба Ink)"""
    arteries(A)
    veins(V)
