"""Спинной мозг и нервы: цвет, рисунок на схеме тела (2D) и модель для 3D-просмотра.

На схеме - спинной мозг в позвоночном канале (от продолговатого мозга до первого-второго поясничного
позвонка, ниже - «конский хвост»), корешки спинномозговых нервов, межрёберные нервы и крупные нервы
рук (из плечевого сплетения) и ног (бедренные). Самый нижний слой схемы: в шее, груди и животе его закрывают
другие органы, а нервы рук и ног видны.
"""

import numpy as np

from ..colors import hex2rgb
from ..geometry import CX, P
from ..models import load_parts
from ..render2d.noise import gblur
from ..render2d.organ import Org, finish, shade


# --------------------------------------------------------------- цвет (тексты карточки: lang/*.json)
COLOR = "#e9c34f"                      # цвет органа на схеме и полоски в карточке
SYSTEMS = ("nervous",)                 # системы органов (первая - главная): тема и вопросы викторины


# --------------------------------------------------------------- 2D: рисунок на схеме тела

TOP, CONUS, TAIL = 98, 278, 344        # начало спинного мозга, его конец (L1-L2) и конец «конского хвоста»
CORD = [(0, TOP), (0, 128), (0, 148), (0, 200), (0, 250), (0, 262), (0, 272), (0, CONUS)]
CORD_W = [7.2, 8.2, 8.0, 6.2, 6.0, 7.0, 5.4, 1.8]                      # утолщения: шейное и поясничное
LEVELS = [104 + 7 * i for i in range(8)] + [160 + 8.6 * i for i in range(12)] + [268 + 11 * i for i in range(5)]
# нервы руки (правой; левая зеркальная): срединный идёт рядом с плечевой артерией, локтевой - ближе к телу
ARM = (([(4, 128), (16, 140), (32, 152), (50, 153), (66, 159), (77, 179), (82, 214), (87, 252), (92, 284),
         (99, 330), (104, 370), (106, 390)], [2.8, 2.8, 2.6, 2.4, 2.2, 2.0, 1.9, 1.8, 1.6, 1.4, 1.2, 1.0]),
       ([(4, 148), (22, 152), (50, 156), (64, 166), (71, 186), (74, 214), (79, 252), (86, 286), (94, 330),
         (100, 372), (101, 388)], [2.4, 2.4, 2.2, 2.0, 1.8, 1.7, 1.6, 1.4, 1.2, 1.0, 0.9]))
# бедренный нерв (правый): из поясничного сплетения под паховой связкой на бедро, снаружи от артерии
HIT_PAD = 1.2                          # запас вокруг нервов для попадания мышью
LEG = ([(3, 286), (10, 300), (20, 326), (30, 356), (34, 380), (32, 400), (31, 430), (30, 468)],
       [2.6, 2.6, 2.6, 2.6, 2.4, 2.2, 1.8, 1.2])


def paint(Z, ss, seed=67):
    o = Org((CX - 110, 92, CX + 110, 476), Z, ss, seed)
    cord = o.ink("cord")
    cord.tube(P(CORD), CORD_W)
    nerves = o.ink("nerves")
    for flip in (False, True):
        for y in LEVELS:                                                # корешки
            if y < CONUS:
                nerves.line(P([(2, y), (7, y + 2), (11, y + 5)], flip), 1.5)
        for k in range(6):                                              # «конский хвост»
            dx = 0.6 + 1.1 * k
            nerves.line(P([(0.6, CONUS - 6), (dx * 0.6, 300), (dx, TAIL - 4 * k)], flip), 1.0)
        for y in LEVELS[13:20]:                                         # межрёберные нервы вдоль рёбер
            nerves.line(P([(10, y + 4), (30, y + 2), (50, y + 8), (63, y + 20)], flip), 1.2)
        for path, widths in ARM + (LEG,):
            nerves.tube(P(path, flip), widths)
    o.L("mask")                                                         # рамка органа (origin) - по маске
    rgba = np.zeros(o.shape + (4,), np.float32)
    rgba = nerves.over(rgba, "#ecd06a", 0.98, amp=1.8, spec=0.35, edge_dark=0.3)
    cov = cord.cov.get()
    fine = o.noise(1.4, 2, 1, stretch=(0.4, 2.0))
    alb = np.broadcast_to(hex2rgb("#f1e2b8"), o.shape + (3,)).copy() * (1 + 0.05 * fine)[..., None]
    body = shade(o, alb, 0.05 * fine + gblur(cord.hgt.get(), 0.5 * Z) * 0.6, cov, soft=(1.2, 2.6),
                 amp=(1.6, 2.0), spec=0.4, shin=16, ambient=0.5)
    a = body[..., 3:4]
    rgba = np.dstack([body[..., :3] * a + rgba[..., :3] * rgba[..., 3:4] * (1 - a),
                      a + rgba[..., 3:4] * (1 - a)])
    rgba[..., :3] /= np.maximum(rgba[..., 3:4], 1e-5)
    hit = np.clip(gblur(rgba[..., 3], HIT_PAD * Z) * 3.0, 0, 1)          # нервы тонкие: попасть мышью легче
    return finish(o, rgba, np.maximum(rgba[..., 3], hit))


# --------------------------------------------------------------- 3D: модель (данные в models/spinal_cord.json)

def parts():
    """3D-модель: примитивы из models/spinal_cord.json"""
    return load_parts("spinal_cord")
