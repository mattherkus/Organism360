"""Аорта: цвет, рисунок на схеме тела (2D) и модель для 3D-просмотра.

На схеме - восходящая аорта, дуга с ветвями (плечеголовной ствол, левые общая сонная и подключичная артерии)
и нисходящая аорта до деления на подвздошные артерии. Лежит под сердцем (оно закрывает корень аорты
и грудную часть), но над лёгкими и трахеей; органы живота и диафрагма закрывают брюшную часть (BEHIND).
"""

import numpy as np

from ..geometry import CX, P
from ..models import load_parts
from ..render2d.organ import Org, finish


# --------------------------------------------------------------- цвет (тексты карточки: lang/*.json)
COLOR = "#d93a43"                      # цвет органа на схеме и полоски в карточке
SYSTEMS = ("circulatory",)             # системы органов (первая - главная): тема и вопросы викторины
# органы перед аортой, хотя они ниже в стопке слоёв (organs.BEHIND): брюшная аорта лежит за ними
BEHIND = ("diaphragm", "liver", "gallbladder", "stomach", "pancreas", "spleen", "intestines",
          "appendix", "rectum", "kidneys", "adrenals", "bladder", "uterus", "ovaries", "prostate")


# --------------------------------------------------------------- 2D: рисунок на схеме тела

ASCENDING = [(3, 207), (3, 192), (6, 178), (14, 168), (24, 168), (31, 176), (33, 190)]   # от сердца через дугу
ASCENDING_W = [13.5, 13.5, 13, 12.5, 12, 11.5, 11]
# нисходящая аорта: за сердцем вниз, слева от позвоночника, до деления на подвздошные артерии
DESCENDING = [(33, 190), (31, 202), (23, 213), (14, 226), (10, 242), (8, 262), (6, 290), (5, 320), (3, 350),
              (2, 371)]
DESCENDING_W = [11, 10.5, 10, 9.5, 9, 8.8, 8.4, 8, 7.4, 6.6]
BRANCHES = (                                                     # (путь, толщины)
    ([(7, 173), (0, 160), (-6, 150)], [6, 5.6, 5.2]),           # плечеголовной ствол
    ([(-6, 150), (-20, 147), (-30, 150)], [5.2, 4.8, 4.2]),     # правая подключичная
    ([(-6, 150), (-8, 143), (-9, 140)], [4.8, 4.6, 4.4]),       # правая общая сонная
    ([(16, 168), (14, 154), (12, 146)], [5.4, 5.2, 5.0]),       # левая общая сонная
    ([(22, 168), (32, 158), (42, 153)], [5.4, 5.1, 4.8]),       # левая подключичная
    ([(6, 268), (12, 272), (16, 271)], [3.2, 2.8, 2.4]),        # чревный ствол
    ([(5, 292), (3, 300), (2, 310)], [3.4, 3.0, 2.6]),          # верхняя брыжеечная артерия
)


def paint(Z, ss, seed=41):
    o = Org((CX - 36, 132, CX + 50, 380), Z, ss, seed)
    ao = o.ink("aorta")
    ao.tube(P(DESCENDING), DESCENDING_W)
    for path, widths in BRANCHES:
        ao.tube(P(path), widths)
    ao.tube(P(ASCENDING), ASCENDING_W)
    o.L("mask")                                                    # рамка органа (origin) - по маске
    rgba = ao.over(np.zeros(o.shape + (4,), np.float32), "#d4343d", 0.99, amp=3.8, spec=0.5, edge_dark=0.42)
    return finish(o, rgba)


# --------------------------------------------------------------- 3D: модель (данные в models/aorta.json)

def parts():
    """3D-модель: примитивы из models/aorta.json"""
    return load_parts("aorta")
