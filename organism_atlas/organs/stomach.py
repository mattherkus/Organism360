"""Желудок: цвет, рисунок на схеме тела (2D) и модель для 3D-просмотра."""

import numpy as np

from ..colors import hex2rgb
from ..geometry import CX, P
from ..models import load_parts
from ..render2d.organ import Org, finish, shade


# --------------------------------------------------------------- цвет (тексты карточки: lang/*.json)
COLOR = "#e0956f"                      # цвет органа на схеме и полоски в карточке
SYSTEMS = ("digestive",)               # системы органов (первая - главная): тема и вопросы викторины


# --------------------------------------------------------------- 2D: рисунок на схеме тела

# желудок чуть меньше и выше, чем «в натуре»: под ним должна быть видна поджелудочная железа
STOMACH = [(4, 253), (9, 247.5), (21, 245), (35, 247.5), (45, 255), (50.5, 266.5), (50.5, 279.5), (46, 291),
           (38.5, 300), (28, 305), (18, 306), (7.5, 302.5), (-1, 297.5), (-8, 294.5), (-14, 291), (-16, 287),
           (-12.5, 283.5), (-4.5, 285.5), (4, 283.5), (11, 279.5), (15, 272), (17, 264), (13.5, 257.5), (8, 255)]


def paint(Z, ss, seed=9):
    o = Org((CX - 26, 232, CX + 66, 316), Z, ss, seed)
    o.L("mask").poly(P(STOMACH))
    o.L("mask").tube(P([(5, 238), (5, 246), (5, 253)]), [8, 8, 8])             # пищевод
    mask = o.m("mask")
    f = o.L("fold")
    for pts in ([(50.5, 268), (40, 271.5), (30, 269.5)], [(50.5, 280.5), (39.5, 284.5), (27, 283.5)],
                [(47, 291), (36, 295), (24.5, 294.5)], [(39.5, 300), (30, 302.5), (19.5, 301)],
                [(45, 256.5), (36.5, 260), (28, 258)]):
        f.line(P(pts), 2.1)
    o.L("vsl").line(P([(47, 265), (48, 278), (43.5, 289.5), (36, 297.5), (26.5, 301.5), (17, 302.5)]), 1.1)
    o.L("vsl_b").line(P([(-3, 285.5), (5.5, 283.5), (12.5, 278.5), (16, 271.5)]), 1.0)
    fold = o.m("fold", 0.9)
    vsl, vsb = o.m("vsl", 0.4), o.m("vsl_b", 0.4)
    alb = np.broadcast_to(hex2rgb("#e89f80"), o.shape + (3,)).copy()
    fib = o.noise(3.4, 3, 4, stretch=(1.7, 0.45))
    big = o.noise(18, 3, 5)
    alb = alb * (1 + 0.028 * fib + 0.035 * big)[..., None]
    alb = alb * (1 - 0.36 * fold[..., None])
    alb = alb * (1 - 0.8 * vsl[..., None]) + hex2rgb("#c92f3a") * 0.8 * vsl[..., None]
    alb = alb * (1 - 0.8 * vsb[..., None]) + hex2rgb("#3d6fb8") * 0.8 * vsb[..., None]
    bump = 0.04 * fib + 0.06 * big - 1.7 * fold
    rgba = shade(o, alb, bump, mask, spec=0.34, shin=14, amp=(5.0, 8.0))
    return finish(o, rgba)


# --------------------------------------------------------------- 3D: модель (данные в models/stomach.json)

