"""Диафрагма: цвет, рисунок на схеме тела (2D) и модель для 3D-просмотра."""

import numpy as np

from ..colors import hex2rgb, mixa
from ..geometry import CX, P
from ..models import load_parts
from ..render2d.organ import Org, finish, shade


# --------------------------------------------------------------- цвет (тексты карточки: lang/*.json)
COLOR = "#b5534d"                      # цвет органа на схеме и полоски в карточке
SYSTEMS = ("respiratory",)             # системы органов (первая - главная): тема и вопросы викторины


# --------------------------------------------------------------- 2D: рисунок на схеме тела

# мышечный купол под лёгкими: правый купол выше (под ним печень), середина - сухожильный центр под сердцем;
# края спускаются к нижним рёбрам. Лежит над печенью, желудком и селезёнкой, под лёгкими и сердцем
DOME = [(-66, 270), (-62, 253), (-50, 247), (-34, 249), (-18, 247), (-6, 249), (6, 254), (20, 255), (34, 258),
        (48, 255), (59, 250), (64, 262), (66, 272)]
DOME_W = [3.6, 5.2, 6.2, 6.4, 6.0, 5.6, 5.4, 5.6, 6.0, 6.4, 6.0, 5.0, 3.6]
TENDON = [(-14, 248), (-4, 249.5), (6, 254), (16, 255)]               # сухожильный центр
# ножки диафрагмы (к позвоночнику) лежат за печенью и желудком: на виде спереди их не видно, они - только в 3D


def paint(Z, ss, seed=59):
    o = Org((CX - 72, 238, CX + 72, 280), Z, ss, seed)
    m = o.L("mask")
    m.tube(P(DOME), DOME_W)
    o.L("tendon").tube(P(TENDON), [4.6, 5.2, 5.2, 4.4])
    mask = o.m("mask")
    tendon = o.m("tendon", 0.8) * mask
    fib = o.noise(1.6, 3, 1, stretch=(1.8, 0.35))                     # волокна вдоль купола
    alb = np.broadcast_to(hex2rgb("#b5534d"), o.shape + (3,)).copy()
    alb = alb * (1 + 0.1 * fib)[..., None]
    alb = mixa(alb, hex2rgb("#e2d6c8") * (1 + 0.04 * fib)[..., None], np.clip(tendon * 0.9, 0, 1))
    bump = 0.22 * fib * (1 - tendon)
    rgba = shade(o, alb, bump, mask, soft=(2.0, 4.0), amp=(2.6, 3.0), spec=0.45, shin=16, ambient=0.5)
    return finish(o, rgba)


